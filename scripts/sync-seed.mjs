// Regenerates the SEED copy of site/events.json inside site/index.html.
// The page falls back to SEED when the fetch fails, so the two must match.
//
//   node scripts/sync-seed.mjs          rewrite the block
//   node scripts/sync-seed.mjs --check  exit 1 if the block is stale

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../site/", import.meta.url));
const page = root + "index.html";
const data = JSON.parse(readFileSync(root + "events.json", "utf8"));

// _howto is for people editing the file, not for the page.
const { _howto, ...seed } = data;
const block = `/* SEED:START — generated by scripts/sync-seed.mjs, do not edit by hand */\nconst SEED = ${JSON.stringify(seed)};\n/* SEED:END */`;

const html = readFileSync(page, "utf8");
const re = /\/\* SEED:START[\s\S]*?\/\* SEED:END \*\//;
if (!re.test(html)) {
  console.error("index.html has no SEED:START / SEED:END block");
  process.exit(1);
}
const next = html.replace(re, block);

if (process.argv.includes("--check")) {
  if (next !== html) {
    console.error("The page's SEED copy is stale. Run: node scripts/sync-seed.mjs");
    process.exit(1);
  }
  console.log("seed matches events.json");
} else if (next !== html) {
  writeFileSync(page, next);
  console.log("seed regenerated");
} else {
  console.log("seed already up to date");
}
